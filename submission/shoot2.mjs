import { chromium } from "@playwright/test";
const b = await chromium.launch({ channel: "chrome", args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader","--ignore-gpu-blocklist"] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.5 });
const page = await ctx.newPage();
const go = async (i, extra = 6000) => {
  await page.goto(`http://127.0.0.1:4173/?chapter=${i}`);
  await page.locator(".veil").waitFor({ state: "detached", timeout: 60000 }).catch(() => {});
  await page.waitForTimeout(extra);
};
const shot = (n) => page.screenshot({ path: `submission/shots/${n}.png` });
await go(5, 12000);
await page.getByRole("button", { name: "Run", exact: true }).click();
await page.waitForTimeout(9000); await shot("ai_mid");
await page.waitForTimeout(20000); await shot("ai_done");
await go(6, 3000);
await page.getByRole("button", { name: "Pause" }).click().catch(() => {});
await page.getByRole("button", { name: /Check A/ }).first().click().catch(() => {});
await page.waitForTimeout(1500); await shot("checks_fail");
await page.getByRole("button", { name: /Check A/ }).last().click().catch(() => {});
await page.waitForTimeout(1500); await shot("checks_pass");
await go(7, 2000); await shot("pictograms");
await go(8, 2000); await shot("learner_ch");
await page.getByRole("button", { name: "Full-screen view" }).click().catch(() => {});
const l = page.locator(".fs");
await l.getByRole("button", { name: "Start" }).click().catch(() => {});
await page.waitForTimeout(1500); await shot("learner_read");
for (let i = 0; i < 5; i++) await l.getByRole("button", { name: /^Next/ }).click().catch(() => {});
await l.getByRole("button", { name: /^Questions/ }).click().catch(() => {});
await page.waitForTimeout(1200); await shot("learner_quiz");
await l.getByRole("button", { name: "Yes" }).click().catch(() => {});
await page.waitForTimeout(1200); await shot("learner_ok");
await go(9, 2000); await shot("results");
await go(4, 8000); await shot("offline");
await go(3, 8000); await shot("load");
await go(10, 2000); await shot("impact");
await b.close();
